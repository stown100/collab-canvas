import type { BoardNote, NoteColor } from '@/shared/store/notesStore';

export interface NoteFields {
  /** Plain-text copy of the note's content, kept for search. */
  body: string;
  color: NoteColor;
}

// Browsers cap the total body of `keepalive` requests at 64 KB.
const KEEPALIVE_MAX_BYTES = 60 * 1024;

export class NotesApiError extends Error {
  constructor(readonly status: number) {
    super(`Notes request failed: ${status}`);
  }
}

async function parse<T>(res: Response): Promise<T> {
  if (!res.ok) throw new NotesApiError(res.status);
  return res.json() as Promise<T>;
}

export async function fetchNotes(boardId: string): Promise<BoardNote[]> {
  const res = await fetch(`/api/boards/${boardId}/notes`, { cache: 'no-store' });
  return parse<BoardNote[]>(res);
}

// `id` is generated by the client so the note can be typed into right away.
export async function createNote(boardId: string, id: string, fields: NoteFields): Promise<BoardNote> {
  const res = await fetch(`/api/boards/${boardId}/notes`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ id, ...fields }),
  });
  return parse<BoardNote>(res);
}

export async function updateNote(
  boardId: string,
  noteId: string,
  patch: Partial<NoteFields>,
): Promise<BoardNote> {
  const body = JSON.stringify(patch);
  const res = await fetch(`/api/boards/${boardId}/notes/${noteId}`, {
    method: 'PATCH',
    headers: { 'Content-Type': 'application/json' },
    body,
    // Lets the last save finish when the page is closed.
    keepalive: body.length < KEEPALIVE_MAX_BYTES,
  });
  return parse<BoardNote>(res);
}

export async function deleteNote(boardId: string, noteId: string): Promise<void> {
  const res = await fetch(`/api/boards/${boardId}/notes/${noteId}`, { method: 'DELETE' });
  if (!res.ok) throw new NotesApiError(res.status);
}

// The board's notes document (a Yjs update holding every note's content).
export async function fetchNotesDoc(boardId: string): Promise<Uint8Array> {
  const res = await fetch(`/api/boards/${boardId}/notes/doc`, { cache: 'no-store' });
  if (!res.ok) throw new NotesApiError(res.status);
  return new Uint8Array(await res.arrayBuffer());
}

export async function pushNotesDocUpdate(boardId: string, update: Uint8Array): Promise<void> {
  const res = await fetch(`/api/boards/${boardId}/notes/doc`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/octet-stream' },
    body: update as BodyInit,
    keepalive: update.byteLength < KEEPALIVE_MAX_BYTES,
  });
  if (!res.ok) throw new NotesApiError(res.status);
}
