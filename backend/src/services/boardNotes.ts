import { getPool } from './db';

// Board notes are shared by everyone on the board. A row holds a note's
// metadata and a plain-text copy of its content (`body`, kept for search);
// the rich text itself lives in the board's notes document (boardNotesDoc).
// Authorization is assumed to have happened upstream (Next.js); `userId`
// comes from the proxy and is only recorded as the creator / last editor.

export const NOTE_COLORS = ['yellow', 'green', 'blue', 'purple', 'pink', 'orange'] as const;
export type NoteColor = (typeof NOTE_COLORS)[number];

export interface NoteInput {
  body?: string;
  color?: NoteColor;
}

export interface NoteUser {
  id: string;
  name: string | null;
  image: string | null;
}

export interface BoardNote {
  id: string;
  body: string;
  color: NoteColor;
  createdAt: string;
  updatedAt: string;
  createdBy: NoteUser | null;
  updatedBy: NoteUser | null;
}

// Every query exposes the affected rows as the CTE `n`; this joins in the
// creator / last editor so each endpoint returns the same shape.
const SELECT_NOTES = `
  SELECT n.id, n.body, n.color, n.created_at, n.updated_at,
         cu.id AS created_by_id, COALESCE(cu.name, cu.email) AS created_by_name, cu.image AS created_by_image,
         uu.id AS updated_by_id, COALESCE(uu.name, uu.email) AS updated_by_name, uu.image AS updated_by_image
  FROM n
  LEFT JOIN users cu ON cu.id = n.created_by
  LEFT JOIN users uu ON uu.id = n.updated_by`;

interface NoteRow {
  id: string;
  body: string;
  color: NoteColor;
  created_at: Date;
  updated_at: Date;
  created_by_id: string | null;
  created_by_name: string | null;
  created_by_image: string | null;
  updated_by_id: string | null;
  updated_by_name: string | null;
  updated_by_image: string | null;
}

function toUser(id: string | null, name: string | null, image: string | null): NoteUser | null {
  return id ? { id, name, image } : null;
}

function toNote(row: NoteRow): BoardNote {
  return {
    id: row.id,
    body: row.body,
    color: row.color,
    createdAt: row.created_at.toISOString(),
    updatedAt: row.updated_at.toISOString(),
    createdBy: toUser(row.created_by_id, row.created_by_name, row.created_by_image),
    updatedBy: toUser(row.updated_by_id, row.updated_by_name, row.updated_by_image),
  };
}

export async function listNotes(boardId: string): Promise<BoardNote[]> {
  const { rows } = await getPool().query<NoteRow>(
    `WITH n AS (SELECT * FROM board_notes WHERE board_id = $1)
     ${SELECT_NOTES}
     ORDER BY n.created_at DESC`,
    [boardId],
  );
  return rows.map(toNote);
}

// The id is generated by the client, so the note's content can be typed into
// its document fragment before this row exists. Repeating the call with the
// same id (a retried request) returns the existing note; null means the id is
// already taken by a note on another board.
export async function createNote(
  boardId: string,
  noteId: string,
  userId: string,
  input: NoteInput,
): Promise<BoardNote | null> {
  const pool = getPool();
  const { rows } = await pool.query<NoteRow>(
    `WITH n AS (
       INSERT INTO board_notes (id, board_id, body, color, created_by, updated_by)
       VALUES ($1, $2, $3, $4, $5, $5)
       ON CONFLICT (id) DO NOTHING
       RETURNING *
     )
     ${SELECT_NOTES}`,
    [noteId, boardId, input.body ?? '', input.color ?? 'yellow', userId],
  );
  if (rows[0]) return toNote(rows[0]);

  const { rows: existing } = await pool.query<NoteRow>(
    `WITH n AS (SELECT * FROM board_notes WHERE id = $1 AND board_id = $2)
     ${SELECT_NOTES}`,
    [noteId, boardId],
  );
  return existing[0] ? toNote(existing[0]) : null;
}

// Updates only the fields present in `input`. Returns null if the note does
// not exist on this board (e.g. it was deleted by another member).
export async function updateNote(
  boardId: string,
  noteId: string,
  userId: string,
  input: NoteInput,
): Promise<BoardNote | null> {
  const { rows } = await getPool().query<NoteRow>(
    `WITH n AS (
       UPDATE board_notes
       SET body = COALESCE($3, body),
           color = COALESCE($4, color),
           updated_by = $5,
           updated_at = now()
       WHERE id = $1 AND board_id = $2
       RETURNING *
     )
     ${SELECT_NOTES}`,
    [noteId, boardId, input.body ?? null, input.color ?? null, userId],
  );
  return rows[0] ? toNote(rows[0]) : null;
}

export async function deleteNote(boardId: string, noteId: string): Promise<void> {
  await getPool().query('DELETE FROM board_notes WHERE id = $1 AND board_id = $2', [noteId, boardId]);
}
